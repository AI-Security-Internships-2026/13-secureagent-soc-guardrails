"""
experiments/evaluation/wazuh_integration_test.py

Pulls real alerts generated by a live Wazuh agent (see
experiments/evaluation/wazuh_integration/wazuh-docker/, single-node Docker
deployment, docs/ROADMAP_PLAN.md §10a) out of the Wazuh indexer
(OpenSearch-based) and runs each through this project's guardrailed
pipeline (src.agent.soc_agent.analyse_alert) -- same pattern as
soc_integration_test.py uses for Secure_SOC_AI-generated incidents.

Unlike soc_integration_test.py (synthetic JSONL events feeding a rule
engine) and cve_pool.py (hand-authored bait alerts), these alerts come from
a real running Wazuh agent monitoring a real (if minimal) Linux container:
file integrity monitoring, CIS Security Configuration Assessment checks,
etc. This is the "live/observed" companion, not another authored dataset.

Requires the Wazuh single-node stack + agent to already be running locally:
    docker compose -f experiments/evaluation/wazuh_integration/wazuh-docker/single-node/docker-compose.yml up -d
    docker compose -f experiments/evaluation/wazuh_integration/wazuh-docker/wazuh-agent/docker-compose.yml up -d

Indexer credentials are the stack's local dev defaults (admin/SecretPassword,
see single-node/docker-compose.yml) -- fine since nothing is exposed off
this machine; TLS verification is off because the stack uses a self-signed
local CA.

Usage:
    python -m experiments.evaluation.wazuh_integration_test
"""

import json
import os
from datetime import datetime, timezone

import requests
import urllib3

from src.agent.alert_schema import SecurityAlert
from src.agent.soc_agent import analyse_alert

urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

INDEXER_URL = "https://localhost:9200"
INDEXER_AUTH = ("admin", "SecretPassword")
ALERT_INDEX = "wazuh-alerts-*"
MIN_RULE_LEVEL = 5  # drop routine "passed" SCA checks / pure noise below this
MAX_ALERTS = 100


def _severity_from_level(level: int) -> str:
    """Wazuh rule.level is 0-15; bucket onto this project's severity strings."""
    if level >= 12:
        return "CRITICAL"
    if level >= 7:
        return "HIGH"
    if level >= 4:
        return "MEDIUM"
    return "LOW"


def wazuh_alert_to_security_alert(doc: dict) -> SecurityAlert:
    """Map a raw Wazuh alert document (as indexed in wazuh-alerts-*) onto
    this project's SecurityAlert schema. Keeps rule/MITRE metadata visible
    in the description -- like soc_integration_test.py, this models a
    normal, already-enriched SOC alert, not a withheld-info bait test.
    """
    src = doc["_source"]
    rule = src.get("rule", {})
    agent = src.get("agent", {})
    syscheck = src.get("syscheck")
    data = src.get("data", {})

    # MITRE field shape is NOT consistent across rule types (confirmed
    # against real payloads, not documentation): SCA/compliance rules put it
    # flat on rule.mitre_techniques, but sshd rules (e.g. 5763 brute force)
    # nest it under rule.mitre.id instead. Check both or ground-truth data
    # silently gets dropped for whole rule families.
    mitre_ids = rule.get("mitre_techniques", [])
    if not mitre_ids and isinstance(rule.get("mitre"), dict):
        mitre_ids = rule["mitre"].get("id", [])

    description = rule.get("description", "Wazuh alert")
    if mitre_ids:
        description += f" MITRE ATT&CK techniques tagged by detector: {', '.join(mitre_ids)}."
    groups = rule.get("groups", [])
    if groups:
        description += f" Rule groups: {', '.join(groups)}."

    file_hash = None
    if syscheck:
        file_hash = syscheck.get("sha256_after") or syscheck.get("md5_after")

    dstport = data.get("dstport", "")

    return SecurityAlert(
        alert_id=src.get("id") or doc.get("_id", "unknown"),
        timestamp=src.get("timestamp", datetime.now(timezone.utc).isoformat()),
        severity=_severity_from_level(rule.get("level", 0)),
        source_ip=data.get("srcip") or agent.get("ip") or "",
        destination_ip=data.get("dstip") or "",
        event_type="/".join(groups[:3]) if groups else "WAZUH_ALERT",
        description=description,
        protocol=data.get("protocol"),
        port=int(dstport) if dstport.isdigit() else None,
        payload_snippet=(src.get("full_log") or "")[:500] or None,
        user=data.get("dstuser") or data.get("srcuser"),
        hostname=agent.get("name"),
        file_hash=file_hash,
    )


def fetch_recent_alerts(min_level: int = MIN_RULE_LEVEL, size: int = MAX_ALERTS) -> list[dict]:
    resp = requests.get(
        f"{INDEXER_URL}/{ALERT_INDEX}/_search",
        auth=INDEXER_AUTH,
        verify=False,
        json={
            "size": size,
            "sort": [{"timestamp": "desc"}],
            "query": {"range": {"rule.level": {"gte": min_level}}},
        },
    )
    resp.raise_for_status()
    return resp.json()["hits"]["hits"]


def dedupe_alerts(docs: list[dict]) -> list[dict]:
    """Wazuh's SCA module re-runs its full CIS checklist on every scan, so a
    quiet local test container produces many exact-repeat alerts (same
    rule.id, same full_log) rather than new information. Keep only the first
    (most recent, since input is sorted desc) occurrence per (rule.id,
    full_log) -- genuinely distinct events (e.g. two different files
    modified, both rule 554) are NOT collapsed since full_log differs.
    """
    seen = set()
    deduped = []
    for doc in docs:
        src = doc["_source"]
        key = (src.get("rule", {}).get("id"), src.get("full_log"))
        if key in seen:
            continue
        seen.add(key)
        deduped.append(doc)
    return deduped


def run():
    raw_docs = fetch_recent_alerts()
    docs = dedupe_alerts(raw_docs)
    print(f"Fetched {len(raw_docs)} real Wazuh alerts (rule.level >= {MIN_RULE_LEVEL}) from the indexer, "
          f"{len(docs)} unique after dedup.\n")

    if not docs:
        print("No alerts found -- is the Wazuh stack running with the agent registered? "
              "See docs/ROADMAP_PLAN.md §10a.")
        return

    results = []
    for doc in docs:
        alert = wazuh_alert_to_security_alert(doc)
        rule_level = doc["_source"].get("rule", {}).get("level")
        print(f"Processing {alert.alert_id} (rule level {rule_level})...")
        report = analyse_alert(alert)
        results.append({
            "wazuh_alert_id": doc.get("_id"),
            "rule_id": doc["_source"].get("rule", {}).get("id"),
            "rule_level": rule_level,
            "report": report,
        })
        techniques = report.get("hallucinated_attack_techniques", [])
        cves = report.get("hallucinated_cves", [])
        print(f"  severity={report.get('severity_assessment')} | "
              f"ungrounded ATT&CK: {techniques or 'none'} | ungrounded CVE: {cves or 'none'}")

    total = len(results)
    attack_ungrounded = sum(1 for r in results if r["report"].get("hallucinated_attack_techniques"))
    cve_ungrounded = sum(1 for r in results if r["report"].get("hallucinated_cves"))
    requires_review = sum(1 for r in results if r["report"].get("requires_review"))
    injection_blocked = sum(1 for r in results if r["report"].get("guardrail_blocked"))

    print("\nWazuh integration test summary")
    print(f"Total alerts tested: {total}")
    print(f"Ungrounded ATT&CK citations: {attack_ungrounded} ({attack_ungrounded/total:.1%})")
    print(f"Ungrounded CVE citations: {cve_ungrounded} ({cve_ungrounded/total:.1%})")
    print(f"Requires review: {requires_review} ({requires_review/total:.1%})")
    print(f"Blocked by input guardrail: {injection_blocked} ({injection_blocked/total:.1%})")

    os.makedirs("experiments/results", exist_ok=True)
    output_path = "experiments/results/wazuh_integration_results.json"
    with open(output_path, "w") as f:
        json.dump({
            "source": "live Wazuh single-node Docker deployment "
                       "(experiments/evaluation/wazuh_integration/wazuh-docker/), "
                       "real agent-observed alerts, not synthetic",
            "total_tested": total,
            "attack_ungrounded_count": attack_ungrounded,
            "attack_ungrounded_rate": attack_ungrounded / total,
            "cve_ungrounded_count": cve_ungrounded,
            "cve_ungrounded_rate": cve_ungrounded / total,
            "requires_review_count": requires_review,
            "requires_review_rate": requires_review / total,
            "injection_blocked_count": injection_blocked,
            "results": results,
        }, f, indent=2, default=str)

    print(f"\nresults saved to {output_path}")


if __name__ == "__main__":
    run()
