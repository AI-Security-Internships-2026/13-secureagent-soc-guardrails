"""
experiments/evaluation/soc_integration_test.py

Feeds a synthetic security-event stream through Secure SOC AI's own local
detection + correlation layer (github.com/engranaabubakar/Secure_SOC_AI,
MIT licensed) to produce realistic, non-hand-crafted incidents, then runs
each incident through THIS project's guardrailed pipeline (input injection
check -> LLM -> CVE/ATT&CK output grounding) instead of Secure_SOC_AI's own
triage step. Secure_SOC_AI's triage/engine.py and its LLM calls are never
invoked here — only its rule engine and correlator (both pure local Python,
no network) are used, as an independent alert generator.

Rationale: cve_bait_test.py / attack_bait_test.py use small (n=6),
deliberately-authored bait alerts to test grounding under adversarial
conditions. This script complements them with a larger set of realistic,
non-adversarial incidents generated by an independent rule engine, to check
whether the guardrail pipeline holds up outside our own synthetic test data.
Each rule also tags its own ground-truth MITRE ATT&CK technique, which is
recorded per-result for comparison against what the LLM actually cites.

Requires the `secure-soc-ai` package:
    pip install git+https://github.com/engranaabubakar/Secure_SOC_AI.git
Detection rules are vendored under soc_integration/vendored_rules/ (from the
same repo, MIT license) so this experiment is reproducible without depending
on the external repo's live state.

Usage:
    python -m experiments.evaluation.soc_integration_test
"""

import json
import os
from pathlib import Path

from secure_soc_ai.correlate import Correlator
from secure_soc_ai.detect.rule_engine import RuleEngine
from secure_soc_ai.ingest.jsonl_source import JsonlFileSource
from secure_soc_ai.models import Incident

from src.agent.alert_schema import SecurityAlert
from src.agent.soc_agent import analyse_alert

HERE = Path(__file__).parent
EVENTS_PATH = HERE / "soc_integration" / "synthetic_events.jsonl"
RULES_DIR = HERE / "soc_integration" / "vendored_rules"

# Secure_SOC_AI entities are "<field>:<value>" strings (see correlate.py /
# rule_engine.py) — map the field name onto our own SecurityAlert schema.
ENTITY_FIELD_MAP = {
    "src_ip": "source_ip",
    "host": "hostname",
    "user": "user",
}


def incident_to_security_alert(incident: Incident) -> SecurityAlert:
    """Map a Secure SOC AI Incident onto this project's SecurityAlert schema.

    Deliberately preserves whatever MITRE ATT&CK IDs the rule engine tagged
    (unlike attack_bait_test.py, which withholds them on purpose) — this is
    meant to look like a normal, already-enriched SOC alert, not a probe.
    """
    entity_kind, _, entity_value = incident.entity.partition(":")
    field = ENTITY_FIELD_MAP.get(entity_kind)

    rule_names = sorted({a.rule_name for a in incident.alerts})
    mitre_ids = sorted({m for a in incident.alerts for m in a.mitre})
    detail_lines = []
    dest_ip = dest_port = None
    for alert in incident.alerts:
        for event in alert.events:
            snippet = event.command_line or event.message or ""
            if snippet:
                detail_lines.append(f"[{event.host or event.src_ip}] {snippet}")
            if event.dest_ip and dest_ip is None:
                dest_ip, dest_port = event.dest_ip, event.dest_port

    description = (
        f"{incident.title}. Detections: {', '.join(rule_names)}. "
        f"MITRE ATT&CK techniques tagged by detector: {', '.join(mitre_ids) or 'none'}."
    )

    kwargs = dict(
        alert_id=incident.id,
        timestamp=incident.created_at.isoformat(),
        severity=incident.severity.value,
        source_ip=entity_value if field == "source_ip" else "",
        destination_ip=dest_ip or "",
        event_type="/".join(sorted({a.detector for a in incident.alerts})),
        description=description,
        payload_snippet="; ".join(detail_lines[:5]) or None,
        port=dest_port,
    )
    if field == "hostname":
        kwargs["hostname"] = entity_value
    if field == "user":
        kwargs["user"] = entity_value

    return SecurityAlert(**kwargs)


def run():
    rules = RuleEngine.from_directory(RULES_DIR)
    correlator = Correlator()

    incidents_by_id: dict[str, Incident] = {}
    for event in JsonlFileSource(EVENTS_PATH).read():
        for alert in rules.evaluate(event):
            incident, _ = correlator.process(alert)
            if incident is not None:
                incidents_by_id[incident.id] = incident
    for incident in correlator.flush_stale():
        incidents_by_id[incident.id] = incident

    incidents = sorted(incidents_by_id.values(), key=lambda i: i.created_at)
    print(f"Detected {len(incidents)} incidents from the synthetic event stream.\n")

    results = []
    for incident in incidents:
        alert = incident_to_security_alert(incident)
        print(f"Processing {incident.id} ({incident.entity}, {len(incident.alerts)} alert(s))...")
        report = analyse_alert(alert)
        ground_truth_mitre = sorted({m for a in incident.alerts for m in a.mitre})
        results.append({
            "incident_id": incident.id,
            "entity": incident.entity,
            "rule_ids": sorted({a.rule_id for a in incident.alerts}),
            "ground_truth_mitre": ground_truth_mitre,
            "report": report,
        })
        techniques = report.get("hallucinated_attack_techniques", [])
        cves = report.get("hallucinated_cves", [])
        print(f"  severity={report.get('severity_assessment')} | "
              f"ungrounded ATT&CK: {techniques or 'none'} | ungrounded CVE: {cves or 'none'}")

    total = len(results)
    attack_ungrounded = sum(1 for r in results if r["report"].get("hallucinated_attack_techniques"))
    cve_ungrounded = sum(1 for r in results if r["report"].get("hallucinated_cves"))
    requires_review = sum(1 for r in results if r["report"].get("requires_review"))
    injection_blocked = sum(1 for r in results if r["report"].get("guardrail_blocked"))

    print("\nSOC integration test summary")
    print(f"Total incidents tested: {total}")
    print(f"Ungrounded ATT&CK citations: {attack_ungrounded} ({attack_ungrounded/total:.1%})")
    print(f"Ungrounded CVE citations: {cve_ungrounded} ({cve_ungrounded/total:.1%})")
    print(f"Requires review: {requires_review} ({requires_review/total:.1%})")
    print(f"Blocked by input guardrail: {injection_blocked} ({injection_blocked/total:.1%})")

    os.makedirs("experiments/results", exist_ok=True)
    output_path = "experiments/results/soc_integration_results.json"
    with open(output_path, "w") as f:
        json.dump({
            "source": "engranaabubakar/Secure_SOC_AI (rule engine + correlator only; "
                       "triage step replaced by this project's guardrailed pipeline)",
            "total_tested": total,
            "attack_ungrounded_count": attack_ungrounded,
            "attack_ungrounded_rate": attack_ungrounded / total,
            "cve_ungrounded_count": cve_ungrounded,
            "cve_ungrounded_rate": cve_ungrounded / total,
            "requires_review_count": requires_review,
            "requires_review_rate": requires_review / total,
            "injection_blocked_count": injection_blocked,
            "results": results,
        }, f, indent=2, default=str)

    print(f"\nresults saved to {output_path}")


if __name__ == "__main__":
    run()
